#!/usr/bin/env python3
"""Carry the Print kit (tools/printkit/) into every app that prints: Labbook, Archive, Hit Finder, Tempo and the Freezer.

The preview before a print is the page the printer makes: the sheet and margins from `@page`, the app's stylesheet read as the
printer reads it, the document flowed into columns one printable area wide and tall, shown as sheets with the running footer.
An app says what its print root is, how to prepare it and what "Print" does; the kit draws the rest.

    python3 tools/sync_printkit.py            # write
    python3 tools/sync_printkit.py --check    # exit 1 if a target is out of date

Edit the kit in tools/printkit/ only — the copies say so in their first comment.
"""
import sys, re, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGETS = ['apps/labbook/labbook.html', 'apps/archive/archive.html', 'apps/hitfinder/hitfinder.html', 'apps/tempo/tempo.html', 'apps/iceberg/iceberg.html']
KIT = ROOT / 'tools/printkit'
CSS = (KIT / 'printkit.css').read_text(encoding='utf-8').rstrip('\n')
JS = (KIT / 'printkit.js').read_text(encoding='utf-8').rstrip('\n')
CSS_BLK = '/* print-kit:begin — generated by tools/sync_printkit.py from tools/printkit/printkit.css; do not edit here */\n' + CSS + '\n/* print-kit:end */'
JS_BLK = '/* print-kit-js:begin — generated by tools/sync_printkit.py from tools/printkit/printkit.js; do not edit here */\n' + JS + '\n/* print-kit-js:end */'

def patch(src):
    out = src
    for tag, blk, wo, wc in (('print-kit', CSS_BLK, '<style>\n', '\n</style>\n'), ('print-kit-js', JS_BLK, '<script>\n', '\n</script>\n')):
        pat = re.compile(r'/\* ' + re.escape(tag) + r':begin.*?/\* ' + re.escape(tag) + r':end \*/', re.S)
        if pat.search(out):
            out = pat.sub(lambda m: blk, out, count=1)
        else:
            i = out.index('\n</head>') + 1
            out = out[:i] + wo + blk + wc + out[i:]
    return out

def main():
    check = '--check' in sys.argv
    bad = 0
    for t in TARGETS:
        p = ROOT / t
        if not p.exists():
            continue
        src = p.read_text(encoding='utf-8')
        new = patch(src)
        if new == src:
            print('current     ', t)
        elif check:
            print('OUT OF DATE ', t); bad += 1
        else:
            p.write_text(new, encoding='utf-8'); print('updated     ', t)
    sys.exit(1 if bad else 0)

if __name__ == '__main__':
    main()
