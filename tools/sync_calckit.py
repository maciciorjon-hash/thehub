#!/usr/bin/env python3
"""Carry the bench calculator (tools/calckit/) into the two searches that can answer it.

Type "10 mM to 50 uM in 1 mL" in the Hub's search (and in Labbook's own, which is the only one in the standalone and phone
builds) and the first row is the pipetting. One engine — dilution, serial dilution, molarity, master mix, unit conversion —
so the two searches cannot disagree about 0.5 % DMSO.

    python3 tools/sync_calckit.py            # write
    python3 tools/sync_calckit.py --check    # exit 1 if a target is out of date

Edit the kit in tools/calckit/ only — the copies say so in their first comment.
"""
import sys, re, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGETS = ['shell/hub-shell.html', 'apps/labbook/labbook.html']
KIT = ROOT / 'tools/calckit'
CSS = (KIT / 'calckit.css').read_text(encoding='utf-8').rstrip('\n')
JS = (KIT / 'calckit.js').read_text(encoding='utf-8').rstrip('\n').replace("if(typeof module!=='undefined'&&module.exports) module.exports=CalcKit;", '').rstrip('\n')
CSS_BLK = '/* calc-kit:begin — generated by tools/sync_calckit.py from tools/calckit/calckit.css; do not edit here */\n' + CSS + '\n/* calc-kit:end */'
JS_BLK = '/* calc-kit-js:begin — generated by tools/sync_calckit.py from tools/calckit/calckit.js; do not edit here */\n' + JS + '\n/* calc-kit-js:end */'

def patch(src):
    out = src
    for tag, blk, wo, wc in (('calc-kit', CSS_BLK, '<style>\n', '\n</style>\n'), ('calc-kit-js', JS_BLK, '<script>\n', '\n</script>\n')):
        pat = re.compile(r'/\* ' + re.escape(tag) + r':begin.*?/\* ' + re.escape(tag) + r':end \*/', re.S)
        if pat.search(out):
            out = pat.sub(lambda m: blk, out, count=1)
        else:
            i = out.index('\n</head>') + 1
            out = out[:i] + wo + blk + wc + out[i:]
    return out

def main():
    check = '--check' in sys.argv
    bad = 0
    for t in TARGETS:
        p = ROOT / t
        src = p.read_text(encoding='utf-8')
        new = patch(src)
        if new == src:
            print('current     ', t)
        elif check:
            print('OUT OF DATE ', t); bad += 1
        else:
            p.write_text(new, encoding='utf-8'); print('updated     ', t)
    sys.exit(1 if bad else 0)

if __name__ == '__main__':
    main()
