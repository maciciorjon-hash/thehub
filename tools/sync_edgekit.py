#!/usr/bin/env python3
"""Carry the edge-effect kit (tools/edgekit/edge.js) into the apps that normalise to a vehicle control, in the head, ahead of the app's own scripts.

    python3 tools/sync_edgekit.py            # write
    python3 tools/sync_edgekit.py --check    # exit 1 if a target is out of date

Edit the kit in tools/patternkit/ only — the copies say so in their first comment.
"""
import sys, re, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGETS = ['apps/lumina/lumina.html']
JS = (ROOT / 'tools/edgekit/edge.js').read_text(encoding='utf-8').rstrip('\n')
BLK = '/* edge-kit-js:begin — generated by tools/sync_edgekit.py from tools/edgekit/edge.js; do not edit here */\n' + JS + '\n/* edge-kit-js:end */'

def patch(src):
    pat = re.compile(r'/\* edge-kit-js:begin.*?/\* edge-kit-js:end \*/', re.S)
    if pat.search(src):
        return pat.sub(lambda m: BLK, src, count=1)
    i = src.index('\n</head>') + 1
    return src[:i] + '<script>\n' + BLK + '\n</script>\n' + src[i:]

def main():
    check = '--check' in sys.argv
    bad = 0
    for t in TARGETS:
        p = ROOT / t
        src = p.read_text(encoding='utf-8')
        new = patch(src)
        if new == src:
            print('current     ', t)
        elif check:
            print('OUT OF DATE ', t); bad += 1
        else:
            p.write_text(new, encoding='utf-8'); print('updated     ', t)
    sys.exit(1 if bad else 0)

if __name__ == '__main__':
    main()
