#!/usr/bin/env python3
"""Carry the Menu kit (tools/menukit/) into the three analysis apps that share one chrome: Lumina, Beacon and Tempo.

The Settings button and its panel, the theme switch (one switch, kept in step with the page however the theme changes: the switch, the Hub's setTheme message,
the attribute set from outside) and the pop-up menus (Export, Units): the same component, the same keys, the same ARIA, in all three. An app calls
`MenuKit.init({ redraw })` once, and gives a menu its items either in markup or through `MenuKit.items(id, rows)`.

    python3 tools/sync_menukit.py            # write
    python3 tools/sync_menukit.py --check    # exit 1 if a target is out of date

Edit the kit in tools/menukit/ only — the copies say so in their first comment.
"""
import sys, re, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGETS = ['apps/lumina/lumina.html', 'apps/tempo/tempo.html', 'apps/beacon/beacon.html']
KIT = ROOT / 'tools/menukit'
CSS = (KIT / 'menu.css').read_text(encoding='utf-8').rstrip('\n')
JS = (KIT / 'menu.js').read_text(encoding='utf-8').rstrip('\n')
CSS_BLK = '/* menu-kit:begin — generated by tools/sync_menukit.py from tools/menukit/menu.css; do not edit here */\n' + CSS + '\n/* menu-kit:end */'
JS_BLK = '/* menu-kit-js:begin — generated by tools/sync_menukit.py from tools/menukit/menu.js; do not edit here */\n' + JS + '\n/* menu-kit-js:end */'

def patch(src):
    out = src
    for tag, blk, wo, wc in (('menu-kit', CSS_BLK, '<style>\n', '\n</style>\n'), ('menu-kit-js', JS_BLK, '<script>\n', '\n</script>\n')):
        pat = re.compile(r'/\* ' + re.escape(tag) + r':begin.*?/\* ' + re.escape(tag) + r':end \*/', re.S)
        if pat.search(out):
            out = pat.sub(lambda m: blk, out, count=1)
        else:
            i = out.index('\n</head>') + 1
            out = out[:i] + wo + blk + wc + out[i:]
    return out

def main():
    check = '--check' in sys.argv
    bad = 0
    for t in TARGETS:
        p = ROOT / t
        src = p.read_text(encoding='utf-8')
        new = patch(src)
        if new == src:
            print('current     ', t)
        elif check:
            print('OUT OF DATE ', t); bad += 1
        else:
            p.write_text(new, encoding='utf-8'); print('updated     ', t)
    sys.exit(1 if bad else 0)

if __name__ == '__main__':
    main()
