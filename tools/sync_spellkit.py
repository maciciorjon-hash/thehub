#!/usr/bin/env python3
"""Carry the spelling kit (tools/spellkit/) into Labbook: the engine, its stylesheet and the dictionary.

    python3 tools/sync_spellkit.py            # write
    python3 tools/sync_spellkit.py --check    # exit 1 if the target is out of date

Edit the kit in tools/spellkit/ only (the dictionary is built by tools/spellkit/build_dict.py) — the copies say so in
their first comment. The dictionary rides as an inert <script type="text/plain"> that is read, inflated and emptied
once, so the page does not carry it twice.
"""
import sys, re, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGETS = ['apps/labbook/labbook.html']
KIT = ROOT / 'tools/spellkit'
CSS = (KIT / 'spellkit.css').read_text(encoding='utf-8').rstrip('\n')
JS = (KIT / 'spellkit.js').read_text(encoding='utf-8').rstrip('\n')
DICT = (KIT / 'dict.b64').read_text(encoding='ascii').strip()
assert '</script' not in JS.lower()
CSS_BLK = '/* spell-kit:begin — generated by tools/sync_spellkit.py from tools/spellkit/spellkit.css; do not edit here */\n' + CSS + '\n/* spell-kit:end */'
JS_BLK = '/* spell-kit-js:begin — generated by tools/sync_spellkit.py from tools/spellkit/spellkit.js; do not edit here */\n' + JS + '\n/* spell-kit-js:end */'
DICT_BLK = '<!-- spell-kit-dict:begin — generated by tools/sync_spellkit.py from tools/spellkit/dict.b64; do not edit here -->\n<script type="text/plain" id="sk-dict">' + DICT + '</script>\n<!-- spell-kit-dict:end -->'

def patch(src):
    out = src
    for tag, blk, wo, wc in (('spell-kit', CSS_BLK, '<style>\n', '\n</style>\n'), ('spell-kit-js', JS_BLK, '<script>\n', '\n</script>\n')):
        pat = re.compile(r'/\* ' + re.escape(tag) + r':begin.*?/\* ' + re.escape(tag) + r':end \*/', re.S)
        if pat.search(out):
            out = pat.sub(lambda m: blk, out, count=1)
        else:
            i = out.index('\n</head>') + 1
            out = out[:i] + wo + blk + wc + out[i:]
    pat = re.compile(r'<!-- spell-kit-dict:begin.*?<!-- spell-kit-dict:end -->', re.S)
    if pat.search(out):
        out = pat.sub(lambda m: DICT_BLK, out, count=1)
    else:
        i = out.index('\n</head>') + 1
        out = out[:i] + DICT_BLK + '\n' + out[i:]
    return out

def main():
    check = '--check' in sys.argv
    bad = 0
    for t in TARGETS:
        p = ROOT / t
        src = p.read_text(encoding='utf-8')
        new = patch(src)
        if new == src:
            print('current     ', t)
        elif check:
            print('OUT OF DATE ', t); bad += 1
        else:
            p.write_text(new, encoding='utf-8'); print('updated     ', t)
    sys.exit(1 if bad else 0)

if __name__ == '__main__':
    main()
