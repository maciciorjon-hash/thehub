#!/usr/bin/env python3
"""Carry the multi-plate reader workbook reader (tools/readerkit/reader_plates.js) into the apps that read plates.

A PHERAstar export can hold every plate of a run: a grid sheet and a settings sheet per plate. RDR finds the plates in
such a workbook; Echo, Lumina and Beacon each decide what a plate does in their own code.

    python3 tools/sync_reader_plates.py            # write
    python3 tools/sync_reader_plates.py --check    # exit 1 if a target is out of date

Edit the kit in tools/readerkit/ only — the copies say so in their first comment.
"""
import sys, re, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGETS = ['apps/echo/echo.html', 'apps/lumina/lumina.html', 'apps/beacon/beacon.html']
JS = (ROOT / 'tools/readerkit/reader_plates.js').read_text(encoding='utf-8').rstrip('\n')
BEGIN = '// ═══ READER PLATES — BEGIN (generated by tools/sync_reader_plates.py from tools/readerkit/reader_plates.js; do not edit here) ═══'
END = '// ═══ READER PLATES — END ═══'
BLK = BEGIN + '\n' + JS + '\n' + END
PAT = re.compile(re.escape('// ═══ READER PLATES — BEGIN') + r'.*?' + re.escape(END), re.S)

def patch(src, anchor):
    if PAT.search(src):
        return PAT.sub(lambda m: BLK, src, count=1)
    i = src.index(anchor)
    return src[:i] + BLK + '\n' + src[i:]

# Where the block goes the first time: just before the code that reads reader files, so it is defined before use.
ANCHORS = {
    'apps/echo/echo.html': '// ═══ SCREEN ENGINE — BEGIN',
    'apps/lumina/lumina.html': '// ══════════════════════════════════════════════════════════════\n// Reader-file import (signal)',
    'apps/beacon/beacon.html': 'function extractPheraProtocolFields(rows) {',
}

def main():
    check = '--check' in sys.argv
    bad = 0
    for t in TARGETS:
        p = ROOT / t
        if not p.exists():
            continue
        src = p.read_text(encoding='utf-8')
        new = patch(src, ANCHORS[t])
        if new == src:
            print('current     ', t)
        elif check:
            print('OUT OF DATE ', t); bad += 1
        else:
            p.write_text(new, encoding='utf-8'); print('updated     ', t)
    sys.exit(1 if bad else 0)

if __name__ == '__main__':
    main()
