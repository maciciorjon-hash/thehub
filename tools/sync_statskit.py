#!/usr/bin/env python3
"""Carry the descriptive-statistics kit (tools/statskit/stats.js) into every data-analysis app, in the head, ahead of the app's own scripts.

    python3 tools/sync_statskit.py            # write
    python3 tools/sync_statskit.py --check    # exit 1 if a target is out of date

Edit the kit in tools/statskit/ only — the copies say so in their first comment.
"""
import sys, re, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGETS = ['apps/echo/echo.html', 'apps/lumina/lumina.html', 'apps/beacon/beacon.html', 'apps/tempo/tempo.html', 'apps/hitfinder/hitfinder.html', 'apps/dora/dora.html', 'apps/bca/bca.html']
JS = (ROOT / 'tools/statskit/stats.js').read_text(encoding='utf-8').rstrip('\n')
BLK = '/* stats-kit-js:begin — generated by tools/sync_statskit.py from tools/statskit/stats.js; do not edit here */\n' + JS + '\n/* stats-kit-js:end */'

def patch(src):
    pat = re.compile(r'/\* stats-kit-js:begin.*?/\* stats-kit-js:end \*/', re.S)
    if pat.search(src):
        return pat.sub(lambda m: BLK, src, count=1)
    i = src.index('\n</head>') + 1
    return src[:i] + '<script>\n' + BLK + '\n</script>\n' + src[i:]

def main():
    check = '--check' in sys.argv
    bad = 0
    for t in TARGETS:
        p = ROOT / t
        src = p.read_text(encoding='utf-8')
        new = patch(src)
        if new == src:
            print('current     ', t)
        elif check:
            print('OUT OF DATE ', t); bad += 1
        else:
            p.write_text(new, encoding='utf-8'); print('updated     ', t)
    sys.exit(1 if bad else 0)

if __name__ == '__main__':
    main()
