#!/usr/bin/env python3
"""Carry the New-analysis kit (tools/newkit/) into the four analysis apps that have a Setup: Echo, Lumina, Beacon and Tempo.

"New analysis": keep the one on screen, start the next from the beginning with Setup open, or from a copy of this one's inputs. The button and the question
it asks are the kit's; each app says how it empties itself (`blank`) and how it keeps its inputs (`copy`).

    python3 tools/sync_newkit.py            # write
    python3 tools/sync_newkit.py --check    # exit 1 if a target is out of date

Edit the kit in tools/newkit/ only — the copies say so in their first comment.
"""
import sys, re, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGETS = ['apps/echo/echo.html', 'apps/lumina/lumina.html', 'apps/tempo/tempo.html', 'apps/beacon/beacon.html']
KIT = ROOT / 'tools/newkit'
CSS = (KIT / 'new.css').read_text(encoding='utf-8').rstrip('\n')
JS = (KIT / 'new.js').read_text(encoding='utf-8').rstrip('\n')
CSS_BLK = '/* new-kit:begin — generated by tools/sync_newkit.py from tools/newkit/new.css; do not edit here */\n' + CSS + '\n/* new-kit:end */'
JS_BLK = '/* new-kit-js:begin — generated by tools/sync_newkit.py from tools/newkit/new.js; do not edit here */\n' + JS + '\n/* new-kit-js:end */'

def patch(src):
    out = src
    for tag, blk, wo, wc in (('new-kit', CSS_BLK, '<style>\n', '\n</style>\n'), ('new-kit-js', JS_BLK, '<script>\n', '\n</script>\n')):
        pat = re.compile(r'/\* ' + re.escape(tag) + r':begin.*?/\* ' + re.escape(tag) + r':end \*/', re.S)
        if pat.search(out):
            out = pat.sub(lambda m: blk, out, count=1)
        else:
            i = out.index('\n</head>') + 1
            out = out[:i] + wo + blk + wc + out[i:]
    return out

def main():
    check = '--check' in sys.argv
    bad = 0
    for t in TARGETS:
        p = ROOT / t
        src = p.read_text(encoding='utf-8')
        new = patch(src)
        if new == src:
            print('current     ', t)
        elif check:
            print('OUT OF DATE ', t); bad += 1
        else:
            p.write_text(new, encoding='utf-8'); print('updated     ', t)
    sys.exit(1 if bad else 0)

if __name__ == '__main__':
    main()
