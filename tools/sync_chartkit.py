#!/usr/bin/env python3
"""Carry the chart editor (tools/chartkit/) into the apps that draw charts.

ChartKit is the whole editor: a doc of measurements in, an interactive figure out — bars or curves, palettes,
error bars, omitted replicates, titles you drag (snapping to each other and to the plot), PNG at 300/600/1200 dpi,
a vector PDF and SVG. What an app puts in the doc is that app's business; the app mounts it with ChartKit.mount().

    python3 tools/sync_chartkit.py            # write
    python3 tools/sync_chartkit.py --check    # exit 1 if a target is out of date

Edit the kit in tools/chartkit/ only — the copies say so in their first comment.
"""
import sys, re, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGETS = ['apps/beacon/beacon.html', 'apps/lumina/lumina.html', 'apps/echo/echo.html', 'apps/tempo/tempo.html', 'apps/hitfinder/hitfinder.html', 'apps/dora/dora.html', 'apps/bca/bca.html']
KIT = ROOT / 'tools/chartkit'
CSS = (KIT / 'chartkit.css').read_text(encoding='utf-8').rstrip('\n')
JS = '\n'.join((KIT / f).read_text(encoding='utf-8').rstrip('\n') for f in ('ck-core.js', 'ck-export.js', 'ck-ui.js'))
CSS_BLK = '/* chart-kit:begin — generated by tools/sync_chartkit.py from tools/chartkit/chartkit.css; do not edit here */\n' + CSS + '\n/* chart-kit:end */'
JS_BLK = '/* chart-kit-js:begin — generated by tools/sync_chartkit.py from tools/chartkit/*.js; do not edit here */\n' + JS + '\n/* chart-kit-js:end */'

def patch(src):
    out = src
    for tag, blk, wo, wc, anchor in (('chart-kit', CSS_BLK, '<style>\n', '\n</style>\n', '\n</head>'), ('chart-kit-js', JS_BLK, '<script>\n', '\n</script>\n', '\n</body>')):
        pat = re.compile(r'/\* ' + re.escape(tag) + r':begin.*?/\* ' + re.escape(tag) + r':end \*/', re.S)
        if pat.search(out):
            out = pat.sub(lambda m: blk, out, count=1)
        else:
            i = (out.index(anchor) if anchor == '\n</head>' else out.rindex(anchor)) + 1
            out = out[:i] + wo + blk + wc + out[i:]
    return out

def main():
    check = '--check' in sys.argv
    bad = 0
    for t in TARGETS:
        p = ROOT / t
        if not p.exists():
            continue
        src = p.read_text(encoding='utf-8')
        new = patch(src)
        if new == src:
            print('current     ', t)
        elif check:
            print('OUT OF DATE ', t); bad += 1
        else:
            p.write_text(new, encoding='utf-8'); print('updated     ', t)
    sys.exit(1 if bad else 0)

if __name__ == '__main__':
    main()
