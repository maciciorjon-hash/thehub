#!/usr/bin/env python3
"""Carry the Sheet kit (tools/sheetkit/sheet.js) into the apps that write a results workbook.

Every workbook reads from the top down: a sheet is a stack of sections (title, note, table), never one table beside another.

    python3 tools/sync_sheetkit.py            # write
    python3 tools/sync_sheetkit.py --check    # exit 1 if a target is out of date

Edit the kit in tools/sheetkit/ only — the copies say so in their first comment.
"""
import sys, re, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGETS = ['apps/lumina/lumina.html', 'apps/tempo/tempo.html', 'apps/beacon/beacon.html', 'apps/echo/echo.html', 'apps/bca/bca.html']
JS = (ROOT / 'tools/sheetkit/sheet.js').read_text(encoding='utf-8').rstrip('\n')
BLK = '/* sheet-kit-js:begin — generated by tools/sync_sheetkit.py from tools/sheetkit/sheet.js; do not edit here */\n' + JS + '\n/* sheet-kit-js:end */'

def patch(src):
    pat = re.compile(r'/\* sheet-kit-js:begin.*?/\* sheet-kit-js:end \*/', re.S)
    if pat.search(src):
        return pat.sub(lambda m: BLK, src, count=1)
    i = src.index('\n</head>') + 1
    return src[:i] + '<script>\n' + BLK + '\n</script>\n' + src[i:]

def main():
    check = '--check' in sys.argv
    bad = 0
    for t in TARGETS:
        p = ROOT / t
        if not p.exists():
            continue
        src = p.read_text(encoding='utf-8')
        new = patch(src)
        if new == src:
            print('current     ', t)
        elif check:
            print('OUT OF DATE ', t); bad += 1
        else:
            p.write_text(new, encoding='utf-8'); print('updated     ', t)
    sys.exit(1 if bad else 0)

if __name__ == '__main__':
    main()
