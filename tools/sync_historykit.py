#!/usr/bin/env python3
"""Carry the History kit (tools/historykit/) into the analysis apps that keep an analysis under its name.

Echo wrote its own History first (it also keeps versions and a cloud copy); every other app that reads data and fits it gets this one: a list of analyses kept
in the browser's IndexedDB, saved by themselves, searchable, pinnable, renamable, opened as they were left. An app says what to
keep (`current`), how to put it back (`open`) and where the list is drawn.

    python3 tools/sync_historykit.py            # write
    python3 tools/sync_historykit.py --check    # exit 1 if a target is out of date

Edit the kit in tools/historykit/ only — the copies say so in their first comment.
"""
import sys, re, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGETS = ['apps/lumina/lumina.html', 'apps/tempo/tempo.html', 'apps/beacon/beacon.html', 'apps/bca/bca.html']
KIT = ROOT / 'tools/historykit'
CSS = (KIT / 'history.css').read_text(encoding='utf-8').rstrip('\n')
JS = (KIT / 'history.js').read_text(encoding='utf-8').rstrip('\n')
CSS_BLK = '/* history-kit:begin — generated by tools/sync_historykit.py from tools/historykit/history.css; do not edit here */\n' + CSS + '\n/* history-kit:end */'
JS_BLK = '/* history-kit-js:begin — generated by tools/sync_historykit.py from tools/historykit/history.js; do not edit here */\n' + JS + '\n/* history-kit-js:end */'

def patch(src):
    out = src
    for tag, blk, wo, wc in (('history-kit', CSS_BLK, '<style>\n', '\n</style>\n'), ('history-kit-js', JS_BLK, '<script>\n', '\n</script>\n')):
        pat = re.compile(r'/\* ' + re.escape(tag) + r':begin.*?/\* ' + re.escape(tag) + r':end \*/', re.S)
        if pat.search(out):
            out = pat.sub(lambda m: blk, out, count=1)
        else:
            i = out.index('\n</head>') + 1
            out = out[:i] + wo + blk + wc + out[i:]
    return out

def main():
    check = '--check' in sys.argv
    bad = 0
    for t in TARGETS:
        p = ROOT / t
        if not p.exists():
            continue
        src = p.read_text(encoding='utf-8')
        new = patch(src)
        if new == src:
            print('current     ', t)
        elif check:
            print('OUT OF DATE ', t); bad += 1
        else:
            p.write_text(new, encoding='utf-8'); print('updated     ', t)
    sys.exit(1 if bad else 0)

if __name__ == '__main__':
    main()
