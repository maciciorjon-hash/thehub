#!/usr/bin/env python3
"""Carry the structure kit (tools/chemkit/acs.js: every 2D structure in ChemDraw ACS 1996 proportions) into Dora, Echo and Hit Finder, in the head, ahead of the apps own scripts.

    python3 tools/sync_chemkit.py            # write
    python3 tools/sync_chemkit.py --check    # exit 1 if a target is out of date

Edit the kit in tools/chemkit/ only — the copies say so in their first comment.
"""
import sys, re, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGETS = ['apps/dora/dora.html', 'apps/echo/echo.html', 'apps/hitfinder/hitfinder.html']
JS = (ROOT / 'tools/chemkit/acs.js').read_text(encoding='utf-8').rstrip('\n')
BLK = '/* chem-kit-js:begin — generated by tools/sync_chemkit.py from tools/chemkit/acs.js; do not edit here */\n' + JS + '\n/* chem-kit-js:end */'

def patch(src):
    pat = re.compile(r'/\* chem-kit-js:begin.*?/\* chem-kit-js:end \*/', re.S)
    if pat.search(src):
        return pat.sub(lambda m: BLK, src, count=1)
    i = src.index('\n</head>') + 1
    return src[:i] + '<script>\n' + BLK + '\n</script>\n' + src[i:]

def main():
    check = '--check' in sys.argv
    bad = 0
    for t in TARGETS:
        p = ROOT / t
        src = p.read_text(encoding='utf-8')
        new = patch(src)
        if new == src:
            print('current     ', t)
        elif check:
            print('OUT OF DATE ', t); bad += 1
        else:
            p.write_text(new, encoding='utf-8'); print('updated     ', t)
    sys.exit(1 if bad else 0)

if __name__ == '__main__':
    main()
