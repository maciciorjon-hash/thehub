#!/usr/bin/env python3
"""Carry the results-table kit (tools/resultskit/results.css) into the data-analysis apps, as the last stylesheet of the head.

    python3 tools/sync_resultskit.py            # write
    python3 tools/sync_resultskit.py --check    # exit 1 if a target is out of date

Edit the kit in tools/resultskit/ only — the copies say so in their first comment.
"""
import sys, re, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGETS = ['apps/echo/echo.html', 'apps/lumina/lumina.html', 'apps/beacon/beacon.html', 'apps/tempo/tempo.html', 'apps/dora/dora.html']
CSS = (ROOT / 'tools/resultskit/results.css').read_text(encoding='utf-8').rstrip('\n')
BLK = '/* results-kit:begin — generated by tools/sync_resultskit.py from tools/resultskit/results.css; do not edit here */\n' + CSS + '\n/* results-kit:end */'

def patch(src):
    pat = re.compile(r'/\* results-kit:begin.*?/\* results-kit:end \*/', re.S)
    if pat.search(src):
        return pat.sub(lambda m: BLK, src, count=1)
    i = src.index('\n</head>') + 1
    return src[:i] + '<style>\n' + BLK + '\n</style>\n' + src[i:]

def main():
    check = '--check' in sys.argv
    bad = 0
    for t in TARGETS:
        p = ROOT / t
        src = p.read_text(encoding='utf-8')
        new = patch(src)
        if new == src:
            print('current     ', t)
        elif check:
            print('OUT OF DATE ', t); bad += 1
        else:
            p.write_text(new, encoding='utf-8'); print('updated     ', t)
    sys.exit(1 if bad else 0)

if __name__ == '__main__':
    main()
