#!/usr/bin/env python3
"""Carry the Setup dialog (tools/setupkit/) into the apps that are set up before they are read.

Every analysis opens the same way: a dialog of numbered steps with Back / Next, titled groups, a field being a caption over a
control, the plate drawn small beside the steps that lay it out. The kit owns the dialog and the pieces its steps are made of
(group, field, switch, drop zone, plate list, control row, mini plate, review list, typed grid); an app says what its steps are
and what they write into its own state.

    python3 tools/sync_setupkit.py            # write
    python3 tools/sync_setupkit.py --check    # exit 1 if a target is out of date

Edit the kit in tools/setupkit/ only — the copies say so in their first comment.
"""
import sys, re, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGETS = ['apps/beacon/beacon.html', 'apps/lumina/lumina.html', 'apps/echo/echo.html']
KIT = ROOT / 'tools/setupkit'
CSS = (KIT / 'setup.css').read_text(encoding='utf-8').rstrip('\n')
JS = (KIT / 'setup.js').read_text(encoding='utf-8').rstrip('\n')
CSS_BLK = '/* setup-kit:begin — generated by tools/sync_setupkit.py from tools/setupkit/setup.css; do not edit here */\n' + CSS + '\n/* setup-kit:end */'
JS_BLK = '/* setup-kit-js:begin — generated by tools/sync_setupkit.py from tools/setupkit/setup.js; do not edit here */\n' + JS + '\n/* setup-kit-js:end */'

def patch(src):
    out = src
    for tag, blk, wo, wc in (('setup-kit', CSS_BLK, '<style>\n', '\n</style>\n'), ('setup-kit-js', JS_BLK, '<script>\n', '\n</script>\n')):
        pat = re.compile(r'/\* ' + re.escape(tag) + r':begin.*?/\* ' + re.escape(tag) + r':end \*/', re.S)
        if pat.search(out):
            out = pat.sub(lambda m: blk, out, count=1)
        else:
            i = out.index('\n</head>') + 1
            out = out[:i] + wo + blk + wc + out[i:]
    return out

def main():
    check = '--check' in sys.argv
    bad = 0
    for t in TARGETS:
        p = ROOT / t
        if not p.exists():
            continue
        src = p.read_text(encoding='utf-8')
        new = patch(src)
        if new == src:
            print('current     ', t)
        elif check:
            print('OUT OF DATE ', t); bad += 1
        else:
            p.write_text(new, encoding='utf-8'); print('updated     ', t)
    sys.exit(1 if bad else 0)

if __name__ == '__main__':
    main()
